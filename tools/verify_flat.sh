#!/usr/bin/env bash
# Single-version consolidation gates G-1 .. G-7 (referee report Part VIII §8.11).
#
#   bash tools/verify_flat.sh              # gates G-1..G-4 + G-6/G-7 if available
#   bash tools/verify_flat.sh --repro      # also python3 -m reproduce_all --fast
#   bash tools/verify_flat.sh --full       # also npm run build + numeric gate G-3
#
# Every gate prints PASS/FAIL/SKIP and the script exits non-zero if any gate
# failed, so it can be dropped into CI unchanged.
set -uo pipefail
cd "$(dirname "$0")/.." || exit 1

fails=0; skips=0
say()  { printf '%-6s %s\n' "$1" "$2"; }
fail() { say FAIL "$1"; fails=$((fails+1)); }
pass() { say PASS "$1"; }
skip() { say SKIP "$1"; skips=$((skips+1)); }

REPRO=0; FULL=0
for a in "$@"; do
  [ "$a" = "--repro" ] && REPRO=1
  [ "$a" = "--full" ] && { REPRO=1; FULL=1; }
done

# word-boundary version token: matches v2, V3, "v2_deflate"? no -- (?<![a-z0-9])
# anchors it, so dv30_face_on_kms and r_v2_like_names are NOT false positives.
VTOK='(?<![a-z0-9])[vV][123](?![0-9a-z])'

echo "== G-1 paper: no revision markup, no version narrative =="
n_rev=$(grep -c 'rev{' paper/main.tex paper/targets_table.tex 2>/dev/null | awk -F: '{s+=$2} END{print s+0}')
[ "$n_rev" -eq 0 ] && pass "no \\rev{} spans remain in the manuscript" \
                   || fail "$n_rev \\rev{} spans still present"
n_flag=$(grep -c 'revflag' paper/main.tex || true)
[ "${n_flag:-0}" -eq 0 ] && pass "no \\revflag machinery" || fail "\\revflag still defined"
if grep -qP "$VTOK" paper/main.tex paper/targets_table.tex; then
  fail "version tokens in the manuscript:"; grep -nP "$VTOK" paper/main.tex paper/targets_table.tex | head -5
else
  pass "no v1/v2/v3 tokens in the manuscript"
fi

echo "== G-2 tree: superseded directories and prefixed files are gone =="
if find . -path ./.git -prune -o -regex '.*/.*[vV][123]_.*' -print | grep -q .; then
  fail "prefixed archive/pipeline names remain:"
  find . -path ./.git -prune -o -regex '.*/.*[vV][123]_.*' -print | head -5
else
  pass "no */v[123]_* file names"
fi
for d in paper/v1 paper/v2 paper/v3 src/v2_superseded results/superseded_v2 \
         results/parts/v2_superseded submission/archive_v2 reviews/v2_superseded scratch; do
  if [ -e "$d" ]; then fail "$d still exists"; fi
done
if find . -path ./.git -prune -o -name '*superseded*' -print | grep -q .; then
  fail "a *superseded* path remains"; find . -path ./.git -prune -o -name '*superseded*' -print | head -5
else
  pass "no superseded trees"
fi

echo "== G-3 data keys: archived keys and labels are version-free =="
python3 - <<'PY'
import numpy as np, glob, re, json, sys
pat = re.compile(r'(?<![a-z0-9])v[123](?![0-9a-z])')
bad = []
for f in glob.glob('results/*.npz'):
    a = np.load(f, allow_pickle=True)
    bad += [f + ':' + k for k in a.files if pat.search(k)]
    for k in a.files:
        arr = np.asarray(a[k])
        if arr.dtype.kind in 'SUO' and any(pat.search(str(v)) for v in arr.ravel()):
            bad.append(f + ':label in ' + k)
s = open('results/audit.json').read()
bad += ['audit.json: ' + m for m in re.findall(r'"[^"]*v[123][^"]*"', s, re.I)
        if 'dv30' not in m.lower()]
print(f"  scanned {len(glob.glob('results/*.npz'))} archives + audit.json")
if bad:
    print("  BAD:", bad[:10]); sys.exit(1)
print("  version-free")
PY
rc=$?
[ $rc -eq 0 ] && pass "results/ keys and labels are version-free" \
              || fail "version tokens in results/ (see above)"

echo "== G-4 prose and demo: version-free README/app text =="
targets="README.md results/README.md src/README.md components app"
[ -d docs ] && targets="$targets docs"
# docs/HISTORY.md is the sanctioned record of the rename map: the old tokens
# appear there ON PURPOSE, so that the deleted trees can still be identified.
# Everything else that a reader or the demo touches must be version-free.
if grep -rqP --exclude=HISTORY.md "$VTOK" $targets 2>/dev/null; then
  fail "version tokens in prose/demo text:"; grep -rnP --exclude=HISTORY.md "$VTOK" $targets 2>/dev/null | head -5
else
  pass "prose and demo text are version-free (docs/HISTORY.md exempt)"
fi
# generated blobs are regenerated by src/make_app_*.py, not hand-edited
for f in public/data/project_data.json data/codeSnippets.json; do
  if [ -e "$f" ] && grep -qP "$VTOK" "$f"; then
    fail "$f still carries version tokens (regenerate with src/make_app_*.py)"
  fi
done

echo "== G-5 entry points: imports, reproduction driver, build =="
(cd src && python3 -c "import sglsim, expcommon, run_experiments, make_figures") \
  && pass "pipeline modules import from src/" || fail "pipeline import broken"
python3 -m reproduce_all --help >/dev/null 2>&1 \
  && pass "python3 -m reproduce_all exists and parses" || fail "reproduce_all missing"
if [ -d results/parts ] && [ "$(ls results/parts/*.npz 2>/dev/null | wc -l)" -gt 0 ]; then
  pass "checkpoints present: $(ls results/parts/*.npz | wc -l) unprefixed parts"
fi
if [ "$REPRO" = 1 ]; then
  if python3 -m reproduce_all --fast > /tmp/verify_repro.log 2>&1; then
    pass "reproduce_all --fast exit 0: $(grep -E '^RESULT' /tmp/verify_repro.log | tail -1)"
  else
    fail "reproduce_all --fast nonzero exit (see /tmp/verify_repro.log)"
  fi
else
  skip "reproduce_all --fast (pass --repro to run it)"
fi
if [ "$FULL" = 1 ]; then
  if [ -d node_modules ] && command -v npm >/dev/null; then
    npm run build >/tmp/verify_npm.log 2>&1 && pass "npm run build" \
      || fail "npm run build (see /tmp/verify_npm.log)"
  else
    skip "npm run build (no node_modules; run npm ci first)"
  fi
  if [ -e /tmp/audit_baseline.json ]; then
    # tools/verify_flat.py takes (old, new); the Stage-0 baseline is the pre-refactor
    # copy of audit.json and the current tree is the new side.
    python3 tools/verify_flat.py /tmp/audit_baseline.json results/audit.json \
      >/tmp/verify_numeric.log 2>&1 && pass "numeric gate" \
      || fail "numeric gate (see /tmp/verify_numeric.log)"
  else
    skip "numeric gate (needs /tmp/audit_baseline.json from Stage 0)"
  fi
else
  skip "npm build + numeric gate (pass --full)"
fi

echo "== G-6 tests =="
if python3 -c "import pytest" 2>/dev/null; then
  if python3 -m pytest tests -q -m "not slow" >/tmp/verify_pytest.log 2>&1; then
    pass "$(tail -1 /tmp/verify_pytest.log)"
  else
    fail "pytest (see /tmp/verify_pytest.log)"; tail -5 /tmp/verify_pytest.log
  fi
else
  skip "pytest not installed"
fi

echo "== G-7 Part VII extension archives =="
python3 - <<'PY'
import glob, json, os, sys
ext = sorted(glob.glob('results/ext_*.json'))
if not ext:
    print("  no extension archives"); sys.exit(3)
bad = []
for p in ext:
    d = json.load(open(p))
    for req in ('provenance', 'headline', 'caveats'):
        if req not in d:
            bad.append(f"{os.path.basename(p)}: no '{req}' block")
print(f"  {len(ext)} extension archives checked")
if bad:
    print("  BAD:", bad[:8]); sys.exit(1)
PY
case $? in
  0) pass "extension archives carry provenance/headline/caveats" ;;
  3) skip "extension archives not generated yet (run reproduce_all --ext)" ;;
  *) fail "extension archives incomplete" ;;
esac

echo
echo "gates: $fails failed, $skips skipped"
[ "$fails" -eq 0 ] || exit 1
